#!/usr/bin/env python3
"""Build the complete pinned Goose compiler with the WebAssembly target patch."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PIN = json.loads((HERE / "upstream.json").read_text(encoding="utf-8"))
RUNTIME_FILES = ("runtime.h", "runtime_impl.h", "runtime_threads.h",
                 "runtime_ext.h", "runtime_os.h", "goose.h")


def run(command: list[str], *, cwd: Path | None = None, capture: bool = False) -> str:
    print("+ " + subprocess.list2cmdline(command), flush=True)
    output = None
    if capture:
        output = subprocess.PIPE
    result = subprocess.run(command, cwd=cwd, check=True, text=True,
                            stdout=output)
    return result.stdout or ""


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def regenerate_runtime(source: Path) -> None:
    """Exactly GenRuntimeHeader at the pinned revision, without a bootstrap build."""
    output = ('// Generated by `goose --gen-runtime-header` from src/runtime/. '
              'Do not edit.\n#pragma once\n\nnamespace goose {\n\n'
              'struct RuntimeFile {\n    const char *name;\n    string_view text;\n'
              '};\n\ninline const RuntimeFile runtime_files[] = {\n')
    for name in RUNTIME_FILES:
        # A one-to-one byte mapping mirrors C++ string offsets even in UTF-8
        # comments; the original bytes are restored when the header is written.
        text = (source / "src" / "runtime" / name).read_bytes().decode("latin-1")
        if ')GSRT"' in text:
            raise RuntimeError(f"raw string delimiter in {name}")
        output += f'    {{ "{name}", string_view(\n'
        offset = 0
        while offset < len(text):
            end = min(offset + 8000, len(text))
            if end < len(text):
                newline = text.rfind("\n", offset, end + 1)
                if newline > offset:
                    end = newline + 1
            output += 'R"GSRT(' + text[offset:end] + ')GSRT"\n'
            offset = end
        if not text:
            output += '""\n'
        output += "    ) },\n"
    output += "};\n\n}  // namespace goose\n"
    header = source / "src" / "runtime_inline.h"
    encoded = output.encode("latin-1")
    if not header.exists() or header.read_bytes() != encoded:
        header.write_bytes(encoded)


def source_fingerprint(source: Path) -> str:
    diff = subprocess.check_output(["git", "diff", "--binary", "HEAD"], cwd=source)
    return hashlib.sha256(diff).hexdigest()


def prepare_source(args: argparse.Namespace, build: Path, patch: Path) -> Path:
    source = build / "source"
    stamp = build / "source.json"
    identity = {"revision": PIN["revision"], "patch_sha256": digest(patch)}
    if source.exists():
        if not stamp.is_file():
            raise RuntimeError(f"refusing to change unmanaged source directory: {source}")
        previous = json.loads(stamp.read_text(encoding="utf-8"))
        head = run(["git", "rev-parse", "HEAD"], cwd=source, capture=True).strip()
        if head != previous["revision"] or source_fingerprint(source) != previous["source_diff_sha256"]:
            raise RuntimeError("managed source has local edits; preserve them and use a new --build-dir")
        if any(previous[key] != value for key, value in identity.items()):
            raise RuntimeError("compiler inputs changed; use a fresh --build-dir to preserve the previous build")
        return source
    origin = PIN["repository"]
    if args.source_repo:
        origin = str(args.source_repo.expanduser().resolve())
    # Fetch the immutable commit, not a moving branch or a release label.
    run(["git", "init", str(source)])
    run(["git", "remote", "add", "origin", origin], cwd=source)
    run(["git", "fetch", "--depth", "1", "origin", PIN["revision"]], cwd=source)
    run(["git", "checkout", "--detach", PIN["revision"]], cwd=source)
    run(["git", "apply", "--check", str(patch)], cwd=source)
    run(["git", "apply", str(patch)], cwd=source)
    regenerate_runtime(source)
    identity["source_diff_sha256"] = source_fingerprint(source)
    stamp.write_text(json.dumps(identity, indent=2) + "\n", encoding="utf-8")
    return source


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build" / "goose-wasm")
    parser.add_argument("--source-repo", type=Path,
                        help="fetch the pinned commit from a local Goose clone (offline setup)")
    parser.add_argument("--cmake", default="cmake")
    parser.add_argument("--generator", help="optional CMake generator, e.g. Ninja")
    parser.add_argument("--jobs", type=int, default=min(2, os.cpu_count() or 1))
    parser.add_argument("--build-type", choices=("Release", "Debug"), default="Release")
    args = parser.parse_args()
    try:
        if args.jobs < 1:
            raise RuntimeError("--jobs must be positive")
        cmake = shutil.which(args.cmake)
        if not cmake:
            raise RuntimeError("CMake >=3.27 is required; install it and a C++20 compiler first")
        build = args.build_dir.expanduser().resolve()
        build.mkdir(parents=True, exist_ok=True)
        source = prepare_source(args, build, HERE / PIN["patch"])
        native = build / "native"
        configure = [cmake, "-S", str(source), "-B", str(native),
                     f"-DCMAKE_BUILD_TYPE={args.build_type}", "-DGOOSE_BUILTIN_LIBS="]
        if args.generator:
            configure.extend(["-G", args.generator])
        run(configure)
        run([cmake, "--build", str(native), "--config", args.build_type,
             "--parallel", str(args.jobs)])
        suffix = ""
        if os.name == "nt":
            suffix = ".exe"
        built = native / ("goose" + suffix)
        if not built.is_file():
            built = native / args.build_type / ("goose" + suffix)
        # Verify the Python bootstrap against the upstream generator. This
        # also catches any runtime source forgotten by the embedding step.
        before = digest(source / "src" / "runtime_inline.h")
        header_stat = (source / "src" / "runtime_inline.h").stat()
        env = dict(os.environ, GOOSE_RUNTIME=str(source / "src" / "runtime"))
        subprocess.run([str(built), "--gen-runtime-header"], check=True, env=env)
        after = digest(source / "src" / "runtime_inline.h")
        if before != after:
            # Different literal chunk boundaries are harmless; rebuild from
            # the upstream generator rather than shipping a stale runtime.
            run([cmake, "--build", str(native), "--config", args.build_type,
                 "--parallel", str(args.jobs)])
            state = json.loads((build / "source.json").read_text(encoding="utf-8"))
            state["source_diff_sha256"] = source_fingerprint(source)
            (build / "source.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        else:
            os.utime(source / "src" / "runtime_inline.h",
                     ns=(header_stat.st_atime_ns, header_stat.st_mtime_ns))
        install = build / "bin"
        install.mkdir(exist_ok=True)
        staged_compiler = install / ("." + built.name + ".new")
        shutil.copy2(built, staged_compiler)
        staged_compiler.replace(install / built.name)
        shutil.copytree(source / "stdlib", install / "stdlib", dirs_exist_ok=True)
        shutil.copytree(native / "tcclib", install / "tcclib", dirs_exist_ok=True)
        (install / "include").mkdir(exist_ok=True)
        shutil.copy2(source / "src" / "runtime" / "goose.h", install / "include" / "goose.h")
        shutil.copy2(source / "LICENSE", install / "GOOSE-LICENSE")
        notices = install / "licenses"
        for relative in ("third_party/tinycc/COPYING", "third_party/tinycc/RELICENSING",
                         "third_party/tinycc/README.md", "third_party/cute_spirv/README.md",
                         "third_party/cute_spirv/cute_spirv.h", "third_party/cute_spirv/ckit.h",
                         "third_party/subprocess/README.md", "third_party/subprocess/subprocess.h"):
            original = source / relative
            if original.is_file():
                destination = notices / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(original, destination)
        metadata = {**PIN, "patch_sha256": digest(HERE / PIN["patch"]),
                    "compiler_sha256": digest(install / built.name),
                    "runtime_sha256": after, "source": str(source),
                    "compiler": str(install / built.name)}
        (build / "toolchain.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        print(f"Built {install / built.name}")
        print(f"Activate Emscripten {PIN['emscripten']}, then use {HERE / 'goose_wasm.py'} build.")
        return 0
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"goose-wasm bootstrap: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
